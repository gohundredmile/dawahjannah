    /**
     * Filters and prioritizes supplications based on emotional state, spiritual need, or custom text.
     * Guarantees 100% relevant multiple results and eliminates irrelevant arbitrary fallbacks.
     */
    fun filterDuas(
        feelingId: String?,
        needId: String?,
        customFeeling: String = "",
        customNeed: String = ""
    ): List<SituationDuaItem> {
        val fKey = feelingId?.lowercase()?.trim() ?: ""
        val nKey = needId?.lowercase()?.trim() ?: ""
        val cFeeling = customFeeling.lowercase().trim()
        val cNeed = customNeed.lowercase().trim()

        val hasSelection = fKey.isNotBlank() || nKey.isNotBlank()
        val hasCustomQuery = cFeeling.isNotBlank() || cNeed.isNotBlank()

        if (!hasSelection && !hasCustomQuery) {
            return allDuas
        }

        // Tokenize custom queries for keyword and semantic matching
        val combinedCustom = "$cFeeling $cNeed".trim()
        val customTokens = combinedCustom.split(Regex("[\\s,।]+")).filter { it.length >= 2 }

        val mappedSemanticTags = mutableSetOf<String>()
        for (token in customTokens) {
            synonymMap.forEach { (keyword, mappedTags) ->
                if (token.contains(keyword) || keyword.contains(token)) {
                    mappedSemanticTags.addAll(mappedTags)
                }
            }
        }

        // Score every candidate item
        val scoredList = allDuas.map { item ->
            var score = 0

            // 1. Tag matching with selected Feeling
            if (fKey.isNotBlank()) {
                if (item.feelingTags.contains(fKey)) {
                    score += 50
                }
            }

            // 2. Tag matching with selected Need
            if (nKey.isNotBlank()) {
                if (item.needTags.contains(nKey)) {
                    score += 50
                }
            }

            // Synergy bonus if matching both selected Feeling & Need
            if (fKey.isNotBlank() && nKey.isNotBlank() && item.feelingTags.contains(fKey) && item.needTags.contains(nKey)) {
                score += 40
            }

            // 3. Custom text / semantic search scoring
            if (hasCustomQuery) {
                // Semantic tag bonus
                mappedSemanticTags.forEach { semTag ->
                    if (item.feelingTags.contains(semTag) || item.needTags.contains(semTag)) {
                        score += 35
                    }
                }

                // Text search across title, translation, reference, and context
                for (token in customTokens) {
                    if (item.titleBn.contains(token, ignoreCase = true)) score += 30
                    if (item.banglaTranslation.contains(token, ignoreCase = true)) score += 25
                    if (item.contextAndTafsirBn.contains(token, ignoreCase = true)) score += 15
                    if (item.referenceCitation.contains(token, ignoreCase = true)) score += 10
                    if (item.arabicText.contains(token)) score += 20
                }
            }

            item to score
        }

        val filtered = scoredList
            .filter { it.second > 0 }
            .sortedByDescending { it.second }
            .map { it.first }

        return filtered
    }
